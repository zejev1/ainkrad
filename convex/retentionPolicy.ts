// ======================================================
// БЕЛЫЙ СПИСОК АВТОМАТИЧЕСКОГО УДАЛЕНИЯ
// ======================================================
//
// ТОЛЬКО эти таблицы может трогать
// автоматическая система очистки.
//
// Любая новая таблица Ainkrad
// автоматически считается защищённой,
// пока мы явно не добавим её сюда.
// ======================================================

export const AUTO_DELETE_TABLES = [
  'inputs',

  'messages',

  'cardinalEvents',

  'archivedConversations',

  'participatedTogether',

  'memories',

  'memoryEmbeddings',

  'embeddingsCache',
] as const;

export type AutoDeleteTable =
  typeof AUTO_DELETE_TABLES[number];

const AUTO_DELETE_TABLE_SET =
  new Set<string>(
    AUTO_DELETE_TABLES,
  );

export function isAutoDeleteTable(
  tableName: string,
): tableName is AutoDeleteTable {
  return AUTO_DELETE_TABLE_SET.has(
    tableName,
  );
}

